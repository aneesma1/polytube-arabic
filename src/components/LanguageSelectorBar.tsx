import React, { useState, useRef } from 'react';
import { 
  Globe, 
  Upload, 
  ChevronDown, 
  Check, 
  FileText, 
  Sparkles,
  FileCheck2,
  Cpu,
  Languages
} from 'lucide-react';

export type SubtitleSourceType = 'builtin' | 'autogenerated' | 'custom_srt';

export interface TargetLanguageOption {
  code: string;
  name: string;
  nativeName: string;
  flag: string;
}

export const TARGET_LANGUAGES: TargetLanguageOption[] = [
  { code: 'en', name: 'English', nativeName: 'English', flag: '🇬🇧' },
  { code: 'ml', name: 'Malayalam', nativeName: 'മലയാളം', flag: '🇮🇳' },
  { code: 'hi', name: 'Hindi', nativeName: 'हिन्दी', flag: '🇮🇳' },
  { code: 'ta', name: 'Tamil', nativeName: 'தமிழ்', flag: '🇮🇳' },
  { code: 'ar', name: 'Arabic', nativeName: 'العربية', flag: '🇸🇦' },
  { code: 'ur', name: 'Urdu', nativeName: 'اردو', flag: '🇵🇰' },
  { code: 'id', name: 'Indonesian', nativeName: 'Bahasa Indonesia', flag: '🇮🇩' },
  { code: 'fr', name: 'French', nativeName: 'Français', flag: '🇫🇷' },
  { code: 'es', name: 'Spanish', nativeName: 'Español', flag: '🇪🇸' },
  { code: 'de', name: 'German', nativeName: 'Deutsch', flag: '🇩🇪' },
];

interface LanguageSelectorBarProps {
  sourceType: SubtitleSourceType;
  onChangeSourceType: (type: SubtitleSourceType) => void;
  targetLangCode: string;
  onChangeTargetLang: (lang: TargetLanguageOption) => void;
  targetLangName: string;
  nativeLangName: string;
  onUploadSrtFile?: (file: File) => void;
  customSrtFilename?: string | null;
  customSrtCount?: number;
  theme?: 'light' | 'dark';
  onSwapLanguages?: () => void;
  onOpenNativeStudio?: () => void;
}

export const LanguageSelectorBar: React.FC<LanguageSelectorBarProps> = ({
  sourceType,
  onChangeSourceType,
  targetLangCode,
  onChangeTargetLang,
  targetLangName,
  nativeLangName,
  onUploadSrtFile,
  customSrtFilename,
  customSrtCount = 0,
  theme = 'light',
  onSwapLanguages,
  onOpenNativeStudio,
}) => {
  const [isOpenTargetMenu, setIsOpenTargetMenu] = useState(false);
  const fileInputRef = useRef<HTMLInputElement | null>(null);
  const isLight = theme === 'light';

  const currentTarget = TARGET_LANGUAGES.find((l) => l.code === targetLangCode) || TARGET_LANGUAGES[0];

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file && onUploadSrtFile) {
      onUploadSrtFile(file);
    }
    // reset input so same file can be re-selected if edited
    if (fileInputRef.current) fileInputRef.current.value = '';
  };

  return (
    <div className={`rounded-2xl p-2.5 flex items-center justify-between gap-2.5 flex-wrap border transition-colors shadow-sm ${
      isLight ? 'bg-white border-slate-200 text-slate-800' : 'bg-slate-900/90 border-slate-800 text-slate-100 shadow-md'
    }`}>
      {/* Hidden File Input for .SRT / .VTT Upload */}
      <input
        ref={fileInputRef}
        type="file"
        accept=".srt,.vtt,.txt"
        onChange={handleFileChange}
        className="hidden"
      />

      {/* 1. Source Track Selector: Built-in vs Auto-Generated vs User Uploaded SRT */}
      <div className="flex items-center gap-1.5 flex-wrap">
        <span className={`text-[11px] font-semibold flex items-center gap-1 mr-1 ${isLight ? 'text-slate-500' : 'text-slate-400'}`}>
          <Languages className="w-3.5 h-3.5 text-rose-500" />
          <span>Source Subtitles:</span>
        </span>

        {/* Built-in Verified */}
        <button
          onClick={() => onChangeSourceType('builtin')}
          className={`px-2.5 py-1 rounded-xl text-xs font-semibold border transition-all cursor-pointer flex items-center gap-1.5 ${
            sourceType === 'builtin'
              ? isLight
                ? 'bg-rose-50 text-rose-700 border-rose-300 shadow-sm'
                : 'bg-rose-500/20 text-rose-300 border-rose-500/50 shadow-sm'
              : isLight
              ? 'bg-slate-100 text-slate-600 border-slate-200 hover:bg-slate-200 hover:text-slate-900'
              : 'bg-slate-850 text-slate-400 border-slate-750 hover:text-white hover:bg-slate-800'
          }`}
          title="Creator Verified subtitles with full Tashkeel / Harakat diacritics and roots"
        >
          <FileCheck2 className="w-3.5 h-3.5 text-rose-500" />
          <span>Built-in (تشكيل معتمد)</span>
          {sourceType === 'builtin' && <span className="w-1.5 h-1.5 rounded-full bg-rose-500" />}
        </button>

        {/* Auto-generated ASR */}
        <button
          onClick={() => onChangeSourceType('autogenerated')}
          className={`px-2.5 py-1 rounded-xl text-xs font-semibold border transition-all cursor-pointer flex items-center gap-1.5 ${
            sourceType === 'autogenerated'
              ? isLight
                ? 'bg-amber-50 text-amber-800 border-amber-300 shadow-sm'
                : 'bg-amber-500/20 text-amber-300 border-amber-500/50 shadow-sm'
              : isLight
              ? 'bg-slate-100 text-slate-600 border-slate-200 hover:bg-slate-200 hover:text-slate-900'
              : 'bg-slate-850 text-slate-400 border-slate-750 hover:text-white hover:bg-slate-800'
          }`}
          title="Raw speech recognition automatic captions directly from YouTube audio"
        >
          <Cpu className="w-3.5 h-3.5 text-amber-500" />
          <span>Auto ASR</span>
          {sourceType === 'autogenerated' && <span className="w-1.5 h-1.5 rounded-full bg-amber-500" />}
        </button>

        {/* If custom SRT is loaded, show toggle button for it */}
        {customSrtCount > 0 && (
          <button
            onClick={() => onChangeSourceType('custom_srt')}
            className={`px-2.5 py-1 rounded-xl text-xs font-semibold border transition-all cursor-pointer flex items-center gap-1.5 ${
              sourceType === 'custom_srt'
                ? isLight
                  ? 'bg-emerald-50 text-emerald-800 border-emerald-300 shadow-sm'
                  : 'bg-emerald-500/20 text-emerald-300 border-emerald-500/50 shadow-sm'
                : isLight
                ? 'bg-slate-100 text-slate-600 border-slate-200 hover:bg-slate-200 hover:text-slate-900'
                : 'bg-slate-850 text-slate-400 border-slate-750 hover:text-white hover:bg-slate-800'
            }`}
            title={`Use your uploaded SRT file (${customSrtFilename || 'Custom SRT'} - ${customSrtCount} lines)`}
          >
            <FileText className="w-3.5 h-3.5 text-emerald-500" />
            <span>Uploaded SRT ({customSrtCount})</span>
            {sourceType === 'custom_srt' && <span className="w-1.5 h-1.5 rounded-full bg-emerald-500" />}
          </button>
        )}

        {/* Direct Upload .SRT Button */}
        <button
          onClick={() => fileInputRef.current?.click()}
          className={`px-2.5 py-1 rounded-xl text-xs font-semibold border transition-all cursor-pointer flex items-center gap-1.5 shadow-sm ${
            isLight
              ? 'bg-emerald-50 hover:bg-emerald-100 text-emerald-700 border-emerald-300'
              : 'bg-emerald-600/20 hover:bg-emerald-600/35 border-emerald-500/40 text-emerald-300'
          }`}
          title="Upload your own .SRT or .VTT subtitle file to play with this video"
        >
          <Upload className="w-3.5 h-3.5 text-emerald-500" />
          <span>Upload .SRT File</span>
        </button>
      </div>

      {/* 2. Target Translated Language Dropdown & Quick Actions */}
      <div className="flex items-center gap-2 flex-wrap">
        <div className="relative flex items-center gap-1.5">
          <span className={`text-[11px] font-semibold flex items-center gap-1 ${isLight ? 'text-slate-500' : 'text-slate-400'}`}>
            <Globe className="w-3.5 h-3.5 text-indigo-500" />
            <span>Translate to:</span>
          </span>

          <button
            onClick={() => setIsOpenTargetMenu(!isOpenTargetMenu)}
            className={`px-3 py-1 rounded-xl text-xs font-semibold flex items-center gap-1.5 transition-all cursor-pointer shadow-sm border ${
              isLight 
                ? 'bg-slate-100 hover:bg-slate-200 border-slate-300 text-slate-800' 
                : 'bg-slate-800 hover:bg-slate-750 border-slate-700 text-slate-200'
            }`}
          >
            <span>{currentTarget.flag}</span>
            <span>{currentTarget.name}</span>
            <ChevronDown className="w-3.5 h-3.5 text-slate-400" />
          </button>

          {/* Dropdown Menu */}
          {isOpenTargetMenu && (
            <div className={`absolute right-0 top-full mt-1.5 z-50 rounded-2xl p-1.5 shadow-2xl w-52 animate-in fade-in duration-150 border ${
              isLight ? 'bg-white border-slate-200 text-slate-800' : 'bg-slate-900 border-slate-700 text-slate-100'
            }`}>
              <div className={`px-2 py-1 text-[10px] font-bold uppercase tracking-wider border-b mb-1 ${
                isLight ? 'text-slate-400 border-slate-100' : 'text-slate-400 border-slate-800'
              }`}>
                Select Target Language
              </div>
              <div className="space-y-0.5 max-h-56 overflow-y-auto">
                {TARGET_LANGUAGES.map((lang) => {
                  const isSelected = lang.code === currentTarget.code;
                  return (
                    <button
                      key={lang.code}
                      onClick={() => {
                        onChangeTargetLang(lang);
                        setIsOpenTargetMenu(false);
                      }}
                      className={`w-full px-2.5 py-1.5 rounded-xl text-xs flex items-center justify-between transition-colors cursor-pointer ${
                        isSelected
                          ? isLight
                            ? 'bg-rose-50 text-rose-700 font-bold'
                            : 'bg-rose-500/20 text-rose-300 font-bold'
                          : isLight
                          ? 'text-slate-700 hover:bg-slate-100 hover:text-black'
                          : 'text-slate-300 hover:bg-slate-800 hover:text-white'
                      }`}
                    >
                      <span className="flex items-center gap-2">
                        <span>{lang.flag}</span>
                        <span>{lang.name}</span>
                        <span className={`text-[10px] ${isLight ? 'text-slate-400' : 'text-slate-400'}`}>({lang.nativeName})</span>
                      </span>
                      {isSelected && <Check className="w-3.5 h-3.5 text-rose-500" />}
                    </button>
                  );
                })}
              </div>
            </div>
          )}
        </div>

        {/* Quick Swap Languages Direction Button */}
        {onSwapLanguages && (
          <button
            onClick={onSwapLanguages}
            className={`px-2.5 py-1 rounded-xl text-xs font-semibold border transition-all cursor-pointer flex items-center gap-1 shadow-sm ${
              isLight 
                ? 'bg-slate-100 hover:bg-slate-200 border-slate-300 text-slate-700' 
                : 'bg-slate-800 hover:bg-slate-750 border-slate-700 text-slate-300'
            }`}
            title="Swap Spoken & Translated Language Direction"
          >
            <span>⇄</span>
            <span className="hidden sm:inline">Swap Direction</span>
          </button>
        )}

        {/* NativeStyle Studio Quick Launch Button */}
        {onOpenNativeStudio && (
          <button
            onClick={onOpenNativeStudio}
            className="px-2.5 py-1 rounded-xl text-xs font-bold bg-gradient-to-r from-rose-500 to-indigo-600 hover:from-rose-600 hover:to-indigo-700 text-white shadow-sm transition-all cursor-pointer flex items-center gap-1.5"
            title="Check expressions in NativeStyle Studio to unlearn calque traps"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>NativeStyle</span>
          </button>
        )}
      </div>
    </div>
  );
};
